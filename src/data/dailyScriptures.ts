/**
 * Returns a deterministic scripture based on the current calendar date (rotating after every midnight 00:00).
 * Supports manual offset browsing as well.
 */
export function getDailyMidnightScripture(manualOffset = 0): {
  scripture: DailyScripture;
  formattedDate: string;
  totalScriptures: number;
  dayIndex: number;
} {
  const now = new Date();
  // Calculate days since Unix epoch in local timezone
  const epochDays = Math.floor((now.getTime() - now.getTimezoneOffset() * 60000) / (1000 * 60 * 60 * 24));
  
  // Deterministic pseudo-random scramble based on day number
  const scrambledDay = (epochDays * 2654435761) >>> 0;
  const rawIndex = (scrambledDay + manualOffset) % SCRIPTURES_COLLECTION.length;
  const dayIndex = ((rawIndex % SCRIPTURES_COLLECTION.length) + SCRIPTURES_COLLECTION.length) % SCRIPTURES_COLLECTION.length;

  const formattedDate = now.toLocaleDateString('en-KE', {
    weekday: 'long',
    month: 'long',
    day: 'numeric',
    year: 'numeric',
  });

  return {
    scripture: SCRIPTURES_COLLECTION[dayIndex],
    formattedDate,
    totalScriptures: SCRIPTURES_COLLECTION.length,
    dayIndex: dayIndex + 1,
  };
}
